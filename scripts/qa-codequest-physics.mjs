import assert from 'node:assert/strict';
import {createPhysics,boxBounds,nearestClear,BODY} from '../projects/codequest-rpg/world-physics.mjs';
const w=createPhysics();
w.add(boxBounds(0,1,0,2,2,2,{walkable:true}));
assert(!w.clear(0,0,0));assert(w.clear(0,0,2));
assert(!w.move({x:-3,z:0},{x:3,z:0},0),'high speed wall tunneling');
assert(w.move({x:-3,z:0},{x:3,z:0},2),'walk over roof');
assert(!w.move({x:-3,z:0},{x:-1.05,z:0},0),'capsule radius');
assert(w.move({x:0,z:0},{x:.5,z:0},0),'escape from old overlap');
w.add(boxBounds(5,2,0,3,.3,3,{walkable:true}));
assert(w.clear(5,0,0));assert(!w.clear(5,0,.7));assert(w.clear(5,0,2.15));
assert.equal(w.ceiling(5,0,0,1.5,2.2)?.minY,1.85);
w.add(boxBounds(-5,.12,0,2,.24,2,{walkable:true}));
assert.equal(w.floor(-5,0,0),.24);
assert(w.move({x:-7,z:0},{x:-5,z:0},0,{step:BODY.step}));
assert.equal(w.surfaces(-5,0).find(p=>p.id==='phys-2').y,.24);
assert(nearestClear(0,0,(x,z)=>w.clear(x,z,0)));
let enabled=false;w.add(boxBounds(10,1,0,2,2,2,{enabled:()=>enabled}));
assert(w.clear(10,0,0));enabled=true;assert(!w.clear(10,0,0));
console.log('PASS shared structural broadphase, radius, sweep, roof, steps, underside, head contact, escape, interaction approach, gated geometry');
